// Reusable sortable + searchable table.
// cols: [{key, label, num?, render?(row)->string|node, sortVal?(row)}]
function buildTable(container, rows, cols, { search = true, initialSort } = {}) {
  container.innerHTML = '';
  let state = { key: initialSort?.key || cols[0].key, dir: initialSort?.dir || 1, q: '' };

  const searchInput = el('input', { type: 'search', placeholder: 'Search constituency, candidate, party…',
    oninput: e => { state.q = e.target.value.toLowerCase(); render(); } });
  if (search) {
    const ctrl = el('div', { class: 'controls' }, searchInput,
      el('span', { class: 'meta', id: 'rowcount', style: 'color:var(--muted);font-size:13px' }));
    container.append(ctrl);
  }
  const wrap = el('div', { class: 'table-wrap' });
  const table = el('table');
  const thead = el('thead'); const htr = el('tr');
  cols.forEach(c => {
    const th = el('th', { class: c.num ? 'num' : '', onclick: () => {
      if (state.key === c.key) state.dir *= -1; else { state.key = c.key; state.dir = 1; }
      render();
    } }, c.label);
    th.dataset.key = c.key; htr.append(th);
  });
  thead.append(htr); table.append(thead);
  const tbody = el('tbody'); table.append(tbody); wrap.append(table); container.append(wrap);

  function render() {
    const sv = r => { const c = cols.find(x => x.key === state.key); return c.sortVal ? c.sortVal(r) : r[state.key]; };
    let data = rows.filter(r => !state.q || cols.some(c => String(r[c.key] ?? '').toLowerCase().includes(state.q)));
    data = data.slice().sort((a, b) => {
      let x = sv(a), y = sv(b);
      if (typeof x === 'string' || typeof y === 'string') { x = String(x ?? ''); y = String(y ?? ''); return state.dir * x.localeCompare(y); }
      return state.dir * ((x ?? -Infinity) - (y ?? -Infinity));
    });
    tbody.innerHTML = '';
    data.forEach(r => {
      const tr = el('tr');
      cols.forEach(c => {
        const td = el('td', { class: c.num ? 'num' : '' });
        const val = c.render ? c.render(r) : (c.num ? fmt(r[c.key]) : (r[c.key] ?? ''));
        if (val?.nodeType) td.append(val); else td.innerHTML = val;
        tr.append(td);
      });
      tbody.append(tr);
    });
    htr.querySelectorAll('th').forEach(th => {
      th.classList.remove('sorted-asc', 'sorted-desc');
      if (th.dataset.key === state.key) th.classList.add(state.dir === 1 ? 'sorted-asc' : 'sorted-desc');
    });
    const rc = document.getElementById('rowcount'); if (rc) rc.textContent = `${data.length} of ${rows.length} rows`;
  }
  render();
}

